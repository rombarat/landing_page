// Writes .env.local for the local stack (HS256 keys signed with the local JWT secret).
import { createHmac, randomBytes } from 'node:crypto'
import { existsSync, writeFileSync } from 'node:fs'

const target = process.argv[2] ?? '.env.local'
if (existsSync(target) && !process.argv.includes('--force')) {
  console.log(`${target} exists, leaving it untouched`)
  process.exit(0)
}
const secret = process.env.JWT_SECRET
const b64 = (v) => Buffer.from(typeof v === 'string' ? v : JSON.stringify(v)).toString('base64url')
const sign = (role) => {
  const head = b64({ alg: 'HS256', typ: 'JWT' })
  const body = b64({ iss: 'supabase-local', role, iat: 1700000000, exp: 2000000000 })
  const sig = createHmac('sha256', secret).update(`${head}.${body}`).digest('base64url')
  return `${head}.${body}.${sig}`
}
writeFileSync(
  target,
  [
    '# Generated by scripts/gen-local-env.mjs for the local stack. Not for production.',
    'NEXT_PUBLIC_SITE_URL=http://localhost:3000',
    'NEXT_PUBLIC_SUPABASE_URL=http://127.0.0.1:54321',
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${sign('anon')}`,
    `SUPABASE_SERVICE_ROLE_KEY=${sign('service_role')}`,
    'DATABASE_URL=postgres://postgres:postgres@127.0.0.1:54322/postgres',
    'STORAGE_DRIVER=local',
    'NEXT_PUBLIC_MEDIA_BASE_URL=/api/storage',
    `ORDER_IP_SALT=${randomBytes(24).toString('hex')}`,
    '',
  ].join('\n'),
)
console.log(`wrote ${target}`)
